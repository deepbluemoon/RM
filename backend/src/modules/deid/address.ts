// 주소 — 시·도 + 시·군·구 + (도로명 N | 동·리 번지) [+ 상세]. 시·도만 있는 표현("서울 소재 법원")은 가리지 않는다
import { collect, type Detector } from './types.js';

const SIDO =
  '(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주|충청북|충청남|전라북|전라남|경상북|경상남)(?:특별시|광역시|특별자치시|특별자치도|도|시)?';
const SIGUNGU = '(?:\\s*[가-힣]{1,6}(?:시|군|구))';
const ROAD = '(?:\\s*[가-힣0-9]{1,12}(?:로|길)\\s*\\d{1,4}(?:-\\d{1,4})?(?:번길\\s*\\d{1,4})?)';
const JIBUN = '(?:\\s*[가-힣0-9]{1,8}(?:동|읍|면|리|가)\\s*(?:산\\s*)?\\d{1,5}(?:-\\d{1,5})?(?:번지)?)';
const DETAIL = '(?:[ ,]*(?:\\d{1,4}동\\s*)?\\d{1,5}호|[ ,]*\\d{1,3}층|[ ,]*\\([가-힣0-9 ,]{1,20}\\))*';
const re = new RegExp(`${SIDO}${SIGUNGU}{1,2}(?:\\s*[가-힣]{1,6}(?:읍|면))?(?:${ROAD}|${JIBUN})${DETAIL}`, 'g');
// 시·도 없이 시작하는 도로명(예: "테헤란로 123")은 주소 문맥어가 앞에 있을 때만
const CTX_ROAD = new RegExp(`(?<=(?:주소|소재지|거주지|주\\s*소)\\s*[:：]?\\s*)[가-힣0-9]{1,12}(?:로|길)\\s*\\d{1,4}(?:-\\d{1,4})?${DETAIL}`, 'g');

export const detectAddress: Detector = (text) => [...collect(re, text, 'address'), ...collect(CTX_ROAD, text, 'address')];
